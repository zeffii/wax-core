// Writes src/app/genexpr_templates.inc from the web app's templates (src/genexpr/templates.js):
//   node tools/gen-genexpr-templates.mjs /path/to/webtracker > src/app/genexpr_templates.inc
import { pathToFileURL } from 'node:url';
import { join } from 'node:path';

const { TEMPLATES } = await import(pathToFileURL(join(process.argv[2], 'src/genexpr/templates.js')).href);
const raw = text => `R"genexpr(${text})genexpr"`;
console.log('// Generated by tools/gen-genexpr-templates.mjs: do not edit.');
console.log('const GenExprTemplate kGenExprTemplates[] = {');
for (const t of TEMPLATES) console.log(`  {${JSON.stringify(t.name)}, ${t.kind === 'instrument'}, ${raw(t.code)}},`);
console.log('};');
