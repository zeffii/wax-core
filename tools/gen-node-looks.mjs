// Writes src/app/node_looks_table.inc from webtracker: each node type's tile shape and glyph, and each glyph as strokes
// (polylines in pixels from the glyph's centre, recorded by running the web app's own drawing code on a recording canvas).
// Run: node tools/gen-node-looks.mjs /path/to/webtracker > src/app/node_looks_table.inc
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2]);
const load = file => import(pathToFileURL(path.join(root, file)).href);
const { NODE_TYPES } = await load('src/audio/nodes/index.js');
const { GLYPHS } = await load('src/graph/glyphs.js');
const types = Array.isArray(NODE_TYPES) ? NODE_TYPES : Object.values(NODE_TYPES);

// The sizes the compact tile gives its glyph (tilelayout.js): [w, h] by shape.
const GLYPH_SIZE = { box: [28, 16], rounded: [28, 16], speaker: [20, 16], circle: [18, 18] };

function record(glyph, w, h) {
  const strokes = [];
  let path = [], pen = null, alpha = 1, fillStyle = false;
  const add = (x, y) => { path.push([x, y]); pen = [x, y]; };
  const arc = (cx, cy, rx, ry, a0, a1, ccw) => {
    let span = a1 - a0;
    if (!ccw && span < 0) span += 2 * Math.PI * Math.ceil(-span / (2 * Math.PI));
    if (ccw && span > 0) span -= 2 * Math.PI * Math.ceil(span / (2 * Math.PI));
    const n = Math.max(8, Math.ceil(Math.abs(span) / (Math.PI / 12)));
    for (let i = 0; i <= n; i++) { const a = a0 + (span * i) / n; path.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]); }
    pen = path[path.length - 1];
  };
  const flush = (fill, closed) => { if (path.length > 1) strokes.push({ fill, alpha, closed, points: path.map(p => p.slice()) }); };
  const ctx = new Proxy({}, {
    get: (_, name) => {
      switch (name) {
        case 'beginPath': return () => { path = []; };
        case 'moveTo': return (x, y) => { if (path.length > 1) { flush(false, false); } path = []; add(x, y); };
        case 'lineTo': return (x, y) => add(x, y);
        case 'closePath': return () => { if (path.length) { path.push(path[0].slice()); } };
        case 'arc': return (x, y, r, a0, a1, ccw) => arc(x, y, r, r, a0, a1, ccw);
        case 'ellipse': return (x, y, rx, ry, rot, a0, a1, ccw) => arc(x, y, rx, ry, a0, a1, ccw);
        case 'quadraticCurveTo': return (cx, cy, x, y) => { const [x0, y0] = pen; for (let i = 1; i <= 12; i++) { const t = i / 12, u = 1 - t; path.push([u * u * x0 + 2 * u * t * cx + t * t * x, u * u * y0 + 2 * u * t * cy + t * t * y]); } pen = [x, y]; };
        case 'bezierCurveTo': return (c1x, c1y, c2x, c2y, x, y) => { const [x0, y0] = pen; for (let i = 1; i <= 16; i++) { const t = i / 16, u = 1 - t; path.push([u ** 3 * x0 + 3 * u * u * t * c1x + 3 * u * t * t * c2x + t ** 3 * x, u ** 3 * y0 + 3 * u * u * t * c1y + 3 * u * t * t * c2y + t ** 3 * y]); } pen = [x, y]; };
        case 'rect': return (x, y, rw, rh) => { path = []; add(x, y); add(x + rw, y); add(x + rw, y + rh); add(x, y + rh); add(x, y); };
        case 'strokeRect': return (x, y, rw, rh) => strokes.push({ fill: false, alpha, closed: true, points: [[x, y], [x + rw, y], [x + rw, y + rh], [x, y + rh], [x, y]] });
        case 'fillRect': return (x, y, rw, rh) => strokes.push({ fill: true, alpha, closed: true, points: [[x, y], [x + rw, y], [x + rw, y + rh], [x, y + rh], [x, y]] });
        case 'stroke': return () => flush(false, false);
        case 'fill': return () => flush(true, true);
        case 'fillText': case 'setLineDash': case 'save': case 'restore': case 'translate': case 'scale': case 'rotate': return () => {};
        case 'measureText': return () => ({ width: 6 });
        default: return undefined;
      }
    },
    set: (_, name, value) => { if (name === 'globalAlpha') alpha = value; return true; },
  });
  glyph(ctx, 0, 0, w, h);
  return strokes;
}

const names = Object.keys(GLYPHS);
const round = v => Math.round(v * 100) / 100;
const out = [];
out.push('// Generated by tools/gen-node-looks.mjs from webtracker (src/audio/nodes, src/graph/glyphs.js). Do not edit by hand.');
out.push('// Glyph strokes: polylines in pixels from the glyph centre, as the compact tile draws them; fill strokes are filled shapes.');
const pointData = [], strokeData = [], glyphData = [];
for (const kind of Object.keys(GLYPH_SIZE)) {
  const [w, h] = GLYPH_SIZE[kind];
  for (const name of names) {
    const first = strokeData.length;
    let strokes = [];
    try { strokes = record(GLYPHS[name], w, h); } catch { strokes = []; }
    for (const s of strokes) {
      strokeData.push(`{${pointData.length / 2}, ${s.points.length}, ${s.fill ? 1 : 0}, ${s.closed ? 1 : 0}, ${round(s.alpha).toFixed(2)}f}`);
      for (const [x, y] of s.points) pointData.push(round(x), round(y));
    }
    glyphData.push(`{"${name}", "${kind}", ${first}, ${strokeData.length - first}}`);
  }
}
out.push(`static const float kGlyphPoints[] = {${pointData.join(', ')}};`);
out.push(`static const GlyphStroke kGlyphStrokes[] = {${strokeData.join(', ')}};`);
out.push(`static const GlyphEntry kGlyphs[] = {${glyphData.join(', ')}};`);
const looks = types.map(d => `{"${d.type}", "${d.shape ?? 'box'}", "${d.glyph ?? ''}", ${d.size ? d.size.w : 0}, ${d.size ? d.size.h : 0}}`);
out.push(`static const NodeLook kLooks[] = {${looks.join(', ')}};`);
console.log(out.join('\n'));
