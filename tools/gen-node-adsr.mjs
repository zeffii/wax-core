// Writes src/app/node_adsr_table.inc from webtracker: which parameters of a node type are an envelope's attack, decay, sustain and release
// (the `adsr` lists of src/audio/nodes/*.js), drawn beside the node when it is selected.
// Run: node tools/gen-node-adsr.mjs /path/to/webtracker > src/app/node_adsr_table.inc
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2]);
const { NODE_TYPES } = await import(pathToFileURL(path.join(root, 'src/audio/nodes/index.js')).href);
const types = Array.isArray(NODE_TYPES) ? NODE_TYPES : Object.values(NODE_TYPES);
const lit = text => JSON.stringify(String(text));

const out = ['// Generated by tools/gen-node-adsr.mjs from webtracker (the adsr lists of src/audio/nodes). Do not edit by hand.', '', 'const NodeEnvelopes kNodeEnvelopes[] = {'];
for (const def of types) {
  if (!def.adsr?.length) continue;
  out.push(`  {${lit(def.type)}, {${def.adsr.map(g => `{${lit(g.atk)}, ${lit(g.dec)}, ${lit(g.sus)}, ${lit(g.rel)}}`).join(', ')}}},`);
}
out.push('};', '');
process.stdout.write(out.join('\n'));
