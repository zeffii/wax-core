// Writes src/app/node_help_table.inc from webtracker: the written help page of each node that has one (src/graph/help.js: summary, best, limits,
// links, sections) and the hint of every parameter of every node (src/graph/hints.js, the common ones filled in).
// Run: node tools/gen-node-help.mjs /path/to/webtracker > src/app/node_help_table.inc
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2]);
const load = file => import(pathToFileURL(path.join(root, file)).href);
const { NODE_TYPES } = await load('src/audio/nodes/index.js');
const { PAGES } = await load('src/graph/help.js');
const { hintFor } = await load('src/graph/hints.js');
const types = Array.isArray(NODE_TYPES) ? NODE_TYPES : Object.values(NODE_TYPES);

// A C++ string literal: printable ASCII as it is, everything else as octal escapes of its UTF-8 bytes (octal stops after three digits, so the
// next character can never be taken into the escape).
const lit = text => {
  let out = '"';
  for (const byte of Buffer.from(String(text), 'utf8')) {
    const ch = String.fromCharCode(byte);
    if (ch === '"' || ch === '\\') out += `\\${ch}`;
    else if (byte >= 32 && byte < 127) out += ch;
    else out += `\\${byte.toString(8).padStart(3, '0')}`;
  }
  return `${out}"`;
};
const list = items => `{${items.map(lit).join(', ')}}`;

const out = ['// Generated by tools/gen-node-help.mjs from webtracker (src/graph/help.js, src/graph/hints.js). Do not edit by hand.', ''];
out.push('const NodeHelp kNodeHelp[] = {');
for (const [type, page] of Object.entries(PAGES)) {
  const links = (page.links ?? []).map(([name, url, note]) => `{${lit(name)}, ${lit(url)}, ${lit(note ?? '')}}`).join(', ');
  const sections = (page.sections ?? []).map(s => `{${lit(s.title)}, ${list(s.text ?? [])}, {${(s.rows ?? []).map(([k, v]) => `{${lit(k)}, ${lit(v)}}`).join(', ')}}}`).join(',\n     ');
  out.push(`  {${lit(type)}, ${lit(page.summary)},\n   ${list(page.best ?? [])},\n   ${list(page.limits ?? [])},\n   {${links}},\n   {${sections}}},`);
}
out.push('};', '', 'const ParamHint kParamHints[] = {');
for (const def of types) for (const spec of def.params ?? []) {
  const hint = hintFor(def.type, spec);
  if (hint) out.push(`  {${lit(def.type)}, ${lit(spec.name)}, ${lit(hint)}},`);
}
out.push('};', '');
process.stdout.write(out.join('\n'));
