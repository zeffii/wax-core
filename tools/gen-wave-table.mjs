// Writes src/nodes/wave_table_data.cpp from webtracker's braids-waves.js: the 256 waves as plain bytes, with the licence.
// Run: node tools/gen-wave-table.mjs /path/to/webtracker/src/audio/nodes/braids-waves.js > src/nodes/wave_table_data.cpp
import fs from 'node:fs';

const source = fs.readFileSync(process.argv[2], 'utf8');
const licence = source.split('\n').filter(line => line.startsWith('//')).join('\n');
const b64 = /`([A-Za-z0-9+/=\s]+)`/.exec(source)[1].replace(/\s+/g, '');
const bytes = Buffer.from(b64, 'base64');
const lines = [];
for (let i = 0; i < bytes.length; i += 32) lines.push('    ' + [...bytes.subarray(i, i + 32)].join(',') + ',');
console.log(`${licence}
//
// Generated by tools/gen-wave-table.mjs; do not edit by hand.
#include "nodes/wave_table_data.h"

namespace wax {

const unsigned char kTableBytes[kTableWaves * kTablePoints] = {
${lines.join('\n')}
};

}  // namespace wax`);
