// Writes src/app/machine_table.inc from webtracker: every kind of instrument that can be added (a fresh instrument as the web app makes
// it) and how the machine tree groups them.
// Run: node tools/gen-machines.mjs /path/to/webtracker > src/app/machine_table.inc
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2]);
const { synthKinds, MACHINE_TREE } = await import(pathToFileURL(path.join(root, 'src/instruments.js')).href);

// A C string literal: printable ASCII as it is, everything else as octal escapes of its UTF-8 bytes.
const literal = text => `"${[...Buffer.from(text, 'utf8')].map(b => (b === 34 ? '\\"' : b === 92 ? '\\\\' : b >= 32 && b < 127 ? String.fromCharCode(b) : `\\${b.toString(8).padStart(3, '0')}`)).join('')}"`;

const out = ['// Generated by tools/gen-machines.mjs from webtracker (src/instruments.js). Do not edit by hand.'];
const kinds = Object.keys(synthKinds).map(kind => {
  const k = synthKinds[kind];
  return `{${literal(kind)}, ${literal(k.label ?? kind)}, ${k.needsSample || k.sampleNode ? 'true' : 'false'}, ${literal(JSON.stringify(k.make()))}}`;
});
out.push(`static const MachineKind kMachineKinds[] = {\n${kinds.join(',\n')}};`);
const leaves = [];
const walk = (group, trail) => {
  const here = [...trail, group.name];
  for (const [kind, name] of group.items ?? []) leaves.push(`{${literal(here.join('/'))}, ${literal(kind)}, ${literal(name)}}`);
  for (const g of group.groups ?? []) walk(g, here);
};
MACHINE_TREE.forEach(g => walk(g, []));
out.push(`static const MachineLeaf kMachineLeaves[] = {${leaves.join(', ')}};`);
console.log(out.join('\n'));
