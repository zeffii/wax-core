// Writes src/app/insert_menu_table.inc from webtracker: the category of each node type and how the add-node menu groups them.
// Run: node tools/gen-insert-menu.mjs /path/to/webtracker > src/app/insert_menu_table.inc
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';

const root = path.resolve(process.argv[2]);
const { NODE_TYPES } = await import(pathToFileURL(path.join(root, 'src/audio/nodes/index.js')).href);
const types = Array.isArray(NODE_TYPES) ? NODE_TYPES : Object.values(NODE_TYPES);

// GROUPS and ORDER are plain data in src/graph/menu.js; evaluate just that part of the file.
const source = fs.readFileSync(path.join(root, 'src/graph/menu.js'), 'utf8');
const start = source.indexOf('const GROUPS = {'), end = source.indexOf('// The hotkey of each row');
const { GROUPS, ORDER } = new Function(`${source.slice(start, end)}; return { GROUPS, ORDER };`)();

const q = s => JSON.stringify(s);
const out = ['// Generated by tools/gen-insert-menu.mjs from webtracker (src/graph/menu.js, src/audio/nodes). Do not edit by hand.'];
out.push(`static const MenuType kMenuTypes[] = {${types.filter(d => !d.master && !d.hidden).map(d => `{${q(d.type)}, ${q(d.category ?? 'Other')}, ${q((d.aliases ?? []).join(' '))}}`).join(', ')}};`);
const groups = [];
for (const [category, list] of Object.entries(GROUPS)) for (const [label, members] of list) for (const type of members) groups.push(`{${q(category)}, ${q(label)}, ${q(type)}}`);
out.push(`static const MenuGroup kMenuGroups[] = {${groups.join(', ')}};`);
out.push(`static const char* const kMenuOrder[] = {${ORDER.map(q).join(', ')}};`);
console.log(out.join('\n'));
